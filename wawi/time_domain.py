import warnings
import numpy as np
from scipy.interpolate import interp1d
from scipy.linalg import block_diag, cholesky, LinAlgError

def band_truncate_3d(M3d, n):
    """ 
    Truncate the bands of a 3D matrix M3d along the first two dimensions.

    Parameters
    ----------
    M3d : np.ndarray
        A 3D numpy array of shape (n, n, m) representing the spectral density matrices for `m` frequency bins.
    n : int
        The number of bands to keep in the truncation.  

    Returns
    -------
    M3d : np.ndarray
        A 3D numpy array of the same shape as `M3d`, where each slice is band-truncated.
        
    Notes
    -----
    Docstring is generated by GitHub Copilot.
    
    """
    for k in range(M3d.shape[2]):
        M3d[:,:,k] = band_truncate(M3d[:,:,k], n=n)
    
    return M3d


def band_truncate(M, n=1):
    """
    Truncate the bands of a 2D matrix M along the first two dimensions.
    
    Parameters
    ----------
    M : np.ndarray
        A 2D numpy array of shape (n, n) representing the spectral density matrix.
    n : int
        The number of bands to keep in the truncation.

    Returns
    -------
    M : np.ndarray
        A 2D numpy array of the same shape as `M`, where each slice is band-truncated.

    Notes
    -----
    Docstring is generated by GitHub Copilot.
    
    """
    if n is None:
        n = M.shape[0]
        
    Mt = M*0

    for ix in range(M.shape[0]):
        n1 = ix-n if (ix-n)>=0 else 0
        n2 = ix+n+1 if (ix+n)<=M.shape[0] else M.shape[0]

        Mt[ix, n1:n2] = M[ix, n1:n2]
    
    return Mt

def fft_time(omega, t0=0, n_fft=None):
    """
    Generate a time vector for FFT based on the frequency vector `omega`.
    
    Parameters
    ----------
    omega : np.ndarray
        A 1D numpy array representing the frequency vector in rad/s.
    t0 : float, optional

        The starting time for the time vector. Default is 0.
    n_fft : int, optional

        The number of points in the FFT. If not provided, it is set to the length of `omega`.

    Returns
    -------
    t : np.ndarray
        A 1D numpy array representing the time vector corresponding to the frequency vector `omega`.

    Notes
    -----
    Docstring is generated by GitHub Copilot.
    
    """
    
    if n_fft is None:
        n_fft = len(omega)
    domega = omega[1] - omega[0] 
    t = np.linspace(t0, np.pi*2/domega, n_fft)

    return t   

def psd_factor(S):
    r"""
    Factor of the nearest positive semi-definite matrix, used when Cholesky decomposition fails.

    Parameters
    ----------
    S : np.ndarray
        Hermitian (cross-spectral density) matrix, 2D array.

    Returns
    -------
    B : np.ndarray
        2D array with :math:`[B][B]^H = [Q][\Lambda_+][Q]^H`.
    min_eig : float
        Smallest eigenvalue of `S` (negative when `S` is indefinite).

    Notes
    -----
    With the eigendecomposition :math:`[S] = [Q][\Lambda][Q]^H`, negative eigenvalues are set to zero
    (:math:`\Lambda_+ = \max(\Lambda, 0)`), which gives the nearest positive semi-definite matrix in the
    Frobenius norm, and the factor :math:`[B] = [Q]\Lambda_+^{1/2}` is returned. In contrast to the
    Cholesky factor, B is not lower triangular; simulations must therefore sum over all columns of B.

    Cross-spectral densities built from coherence models that are not positive definite kernels
    (e.g. exponential decay with the pair-averaged mean wind speed when the mean wind varies between
    points) can be slightly indefinite at the lowest frequencies.
    """
    S = 0.5 * (S + S.conj().T)
    lam, Q = np.linalg.eigh(S)
    return Q * np.sqrt(np.clip(lam, 0.0, None)), lam[0]


def spectrum_to_process(S, reg_factor=None, zero_limit=None, psd_fallback=True):
    """
    Convert a spectral density matrix to its Cholesky factor process.
    This function takes a 3D array representing a spectral density matrix `S` and computes its
    Cholesky factor for each frequency slice. Optional regularization can be applied to ensure positive definiteness,
    and a zero limit can be set to skip decomposition for near-zero matrices.

    Parameters
    ----------
    S : np.ndarray
        A 3D array of shape (n, n, m) representing the spectral density matrices for `m` frequency bins.
    reg_factor : float, optional
        Regularization factor to be added to the diagonal of each frequency slice of `S` to ensure positive definiteness.
    zero_limit : float, optional
        Threshold below which the Cholesky decomposition is skipped for a frequency slice.
    psd_fallback : bool, default=True
        If the Cholesky decomposition fails for a frequency slice (not positive definite), the factor of the
        nearest positive semi-definite matrix is used instead (see `psd_factor`) and a warning is issued.
        If False, the LinAlgError is raised.

    Returns
    -------
    B : np.ndarray
        A 3D array of the same shape as `S`, where each slice is the lower-triangular Cholesky factor of the
        corresponding slice in `S` (or the non-triangular factor from `psd_factor` where Cholesky failed).

    Raises
    ------
    ValueError
        If regularization causes the norm of `S` to increase by more than 10%.

    Notes
    -----
    - The function modifies `S` in-place if regularization is applied.
    - Cholesky decomposition is only performed for slices where the maximum absolute value exceeds `zero_limit`.

    Docstring is generated by GitHub Copilot.
    """

    B = S*0     # copy S to chol factor
    norm_pre = np.linalg.norm(S)
    if reg_factor is not None:
        for k in range(S.shape[2]):
            S[:,:,k] = S[:,:,k] + np.linalg.norm(S[:,:,k]) * np.eye(S.shape[0]) * reg_factor

    if (np.linalg.norm(S)-norm_pre)/norm_pre>0.1:
        raise ValueError('Regularization causes significant increase in norm of S (10%). Please adjust.')

    # Cholesky decomposition (nearest positive semi-definite factor where it fails)
    n_clipped = 0
    worst = 0.0
    for k in range(B.shape[2]):
        if zero_limit is None or np.max(np.max(np.abs(S[:,:,k])))>zero_limit:
            try:
                B[:,:,k] = cholesky(S[:, :, k], lower=True)
            except LinAlgError:
                if not psd_fallback:
                    raise
                B[:,:,k], min_eig = psd_factor(S[:, :, k])
                n_clipped += 1
                worst = min(worst, min_eig / np.mean(np.abs(np.diag(S[:, :, k]))))

    if n_clipped > 0:
        warnings.warn(f'Cross-spectral density not positive definite for {n_clipped} of {B.shape[2]} frequency components; '
                      f'negative eigenvalues clipped to zero (most negative: {worst:.2e} x mean diagonal).',
                      RuntimeWarning, stacklevel=2)
    return B
        

def simulate_mdof(S, omega, fs=None, tmax=None, reg_factor=None, zero_limit=1e-12,
                  phase_angles=None, return_phase_angles=False, interpolation_kind='linear',
                  component_scaling=None, print_status=False, psd_fallback=True):

    r'''
    Simulate time series from given cross-spectral density matrix, using FFT.

    Parameters
    ----------------
    S : float
        cross-spectral density matrix (Ndofs x Ndofs x Nfreqs) as complex numpy array
    omega : float
        numpy array defining frequencies in rad/s
    fs : float, optional
        sampling frequency in Hz; if not given, the value is defined as two times the maximum of `omega`
    tmax : float, optional
        duration of realization in seconds
    reg_factor : float, optional
        to help the Cholesky decomposition to achieve a numerical solution, 
        a diagonal matrix with the norm of all frequency components of the matrix S scaled by the given factor
        - if no value is given (--> None imposed), no regularization is conducted; 
        used as input to function `spectrum_to_process` which decomposes the spectral density 
    zero_limit : float, optional
        frequency components where the norm of S is below this limit is set to zero
        if no value is given (--> None imposed), no zero limit is applied; 
        used as input to function `spectrum_to_process` which decomposes the spectral density 
    phase_angles : float, optional
        if previously conducted simulations are to be recreated, they can by inputting the phase angles
        (to get the phase angles from simulation, see `return_phase_angles` input parameter)
    return_phase_angles : bool, default=False
        whether or not to return phase angle enabling recreation of the simulation
    interpolation_kind : optional, default='linear'
        interpolation type used for interpolation (to ensure that we get defined duration and sampling) prior to ifft
    component_scaling : float, optional
        values to use for scaling of components prior to decomposition (and thereafter rescale afterwards);
        can help if some components are much smaller than others; size should match number of DOFs in S
    print_status : False, optional
        whether or not to print status messages
    psd_fallback : bool, default=True
        if S is not positive definite at a frequency component, use the factor of the nearest positive
        semi-definite matrix instead of failing; passed to `spectrum_to_process`

    Returns
    ----------------
    p : float
        time history
    t : float
        numpy array with time axis values corresponding to `p`
    alpha : float
        phase angles, only returned if `return_phase_angles` is True

    Notes
    ----------------
    The realization holds ``n = round(tmax*fs)`` samples per period, with ``domega = 2*pi/(n/fs)``.
    Frequency component k (``omega_k = k*domega``, k = 1 ... below the Nyquist frequency ``pi*fs``) is placed
    in fft bin k, and each DOF is synthesized as

    .. math::

        p_j(t) = \sum_k \sqrt{2\Delta\omega}\; \mathrm{Re}\Big( \sum_m B_{jm}(\omega_k)\, e^{i\alpha_{mk}}\, e^{-i\omega_k t} \Big)

    by an inverse real FFT. S is interpreted as one-sided per rad/s and is zero outside the range of `omega`
    (no energy below the lowest or above the highest input frequency); the DC component is zero. Content above
    the Nyquist frequency cannot be represented and is dropped with a warning. As the process is periodic,
    the first sample is repeated at the end, so that `t` runs from 0 to tmax (n+1 samples).

    ``phase_angles[m, k]`` belongs to frequency ``omega_k``; arrays with more columns than needed are truncated.
    '''

    if component_scaling is not None:
        c = np.tile(np.array(component_scaling), int(np.round(S.shape[0]/len(component_scaling))))
        scale_mat = c[np.newaxis,:].T @ c[np.newaxis, :]
        for k in range(S.shape[2]):
            S[:,:,k] = scale_mat * S[:,:,k]

    B = spectrum_to_process(S, reg_factor=reg_factor, zero_limit=zero_limit, psd_fallback=psd_fallback)
    B = interp1d(omega, B, axis=2, fill_value=0, kind=interpolation_kind, bounds_error=False)

    n_dofs = S.shape[0]

    if fs is None:
        fs = 2*omega[-1]/(2*np.pi)      # Nyquist frequency equals the largest input frequency

    if tmax is None:
        tmax = 2*np.pi/(omega[1]-omega[0])

    # Time and frequency axes: one period of n samples, omega_sim[k] is placed in fft bin k
    dt = 1/fs
    n = int(round(tmax/dt))
    domega = 2*np.pi/(n*dt)
    n_freqs = n//2 + 1
    omega_sim = np.arange(n_freqs)*domega

    nyquist = np.pi*fs
    if omega[-1] > nyquist*(1+1e-9) and np.any(np.abs(S[:, :, omega > nyquist]) > 0):
        warnings.warn(f'Input spectrum extends to {omega[-1]:.3g} rad/s, above the Nyquist frequency pi*fs = {nyquist:.3g} rad/s; '
                      'content above the Nyquist frequency is not simulated. Increase fs to include it.', RuntimeWarning, stacklevel=2)
    elif fs*2*np.pi > 2*omega[-1]*(1+1e-9) and print_status:
        print('fs higher than twice the largest omega value in input - zero padding automatically enforced')

    if phase_angles is None:
        alpha = 2*np.pi * np.random.rand(n_dofs, n_freqs)
    else:
        alpha = np.asarray(phase_angles)[:, :n_freqs]*1
        if alpha.shape[1] < n_freqs:
            raise ValueError(f'phase_angles has {alpha.shape[1]} frequency columns; {n_freqs} required.')

    # Summation over all columns of B (B is not triangular where the PSD fallback was used)
    Bi = B(omega_sim)
    Bi[:, :, 0] = 0                 # DC
    if n % 2 == 0:
        Bi[:, :, -1] = 0            # Nyquist bin (cannot carry a random phase)

    P = np.einsum('jmk,mk->jk', Bi, np.exp(1j*alpha))
    p = np.fft.irfft(np.conj(P) * n * np.sqrt(domega/2), n=n, axis=1)

    # Periodic process: repeat the first sample so that t covers 0 ... tmax
    p = np.hstack([p, p[:, :1]])
    t = np.arange(n + 1)*dt

    if component_scaling is not None:
        p = p/np.tile(c[:, np.newaxis], reps=p.shape[1])

    if return_phase_angles:
        return p, t, alpha
    else:
        return p, t


def simulate_mdof_direct(S_fun, n_dofs, fs, tmax, omega_min=0.0, omega_max=np.inf, reg_factor=None,
                         zero_limit=1e-12, phase_angles=None, return_phase_angles=False,
                         component_scaling=None, psd_fallback=True, batch_size=64):
    r'''
    Simulate time series from a cross-spectral density given as a function of frequency, using FFT.

    Same realization as `simulate_mdof`, but the cross-spectral density is evaluated and decomposed at every
    fft frequency instead of being decomposed on an input frequency axis and interpolated. It is built for a
    batch of frequencies at a time, decomposed, multiplied by the random phases and discarded, so memory does
    not grow with the number of frequencies (about ``batch_size*n_dofs**2`` values plus the result).

    Parameters
    ----------------
    S_fun : function
        ``S_fun(omega)``, with omega a 1d numpy array (rad/s), returns the cross-spectral density matrices as a
        real or complex numpy array of shape (len(omega), n_dofs, n_dofs); same convention as `S` in
        `simulate_mdof` (one-sided, per rad/s)
    n_dofs : int
        number of DOFs (size of the matrices returned by `S_fun`)
    fs : float
        sampling frequency in Hz
    tmax : float
        duration of realization in seconds
    omega_min, omega_max : float, optional
        frequency band in rad/s; fft frequencies outside it carry no energy (as outside the range of `omega`
        in `simulate_mdof`)
    reg_factor, zero_limit, psd_fallback : optional
        as in `spectrum_to_process`, applied to each frequency component
    phase_angles, return_phase_angles, component_scaling : optional
        as in `simulate_mdof` (same layout, so phase angles can be exchanged between the two functions)
    batch_size : int, default=64
        number of frequency components evaluated and decomposed together

    Returns
    ----------------
    p : float
        time history
    t : float
        numpy array with time axis values corresponding to `p`
    alpha : float
        phase angles, only returned if `return_phase_angles` is True

    Notes
    ----------------
    Time and frequency axes, scaling and phase angles are those of `simulate_mdof`: frequency component k
    (``omega_k = k*domega``, ``domega = 2*pi/(n/fs)``, ``n = round(tmax*fs)``) is placed in fft bin k; DC and
    (for even n) the Nyquist bin are zero. With `simulate_mdof` given ``omega`` equal to the fft frequencies in
    the band and the same phase angles, both functions give the same result to rounding.
    '''
    dt = 1/fs
    n = int(round(tmax/dt))
    domega = 2*np.pi/(n*dt)
    n_freqs = n//2 + 1
    omega_sim = np.arange(n_freqs)*domega

    if phase_angles is None:
        alpha = 2*np.pi * np.random.rand(n_dofs, n_freqs)
    else:
        alpha = np.asarray(phase_angles)[:, :n_freqs]*1
        if alpha.shape[1] < n_freqs:
            raise ValueError(f'phase_angles has {alpha.shape[1]} frequency columns; {n_freqs} required.')

    if component_scaling is not None:
        c = np.tile(np.array(component_scaling), int(np.round(n_dofs/len(component_scaling))))
        scale_mat = c[np.newaxis,:].T @ c[np.newaxis, :]

    nyquist = np.pi*fs
    if np.isfinite(omega_max) and omega_max > nyquist*(1+1e-9):
        warnings.warn(f'omega_max = {omega_max:.3g} rad/s is above the Nyquist frequency pi*fs = {nyquist:.3g} rad/s; '
                      'content above the Nyquist frequency is not simulated. Increase fs to include it.', RuntimeWarning, stacklevel=2)

    # Frequency components to simulate: inside the band, excluding DC and (for even n) the Nyquist bin
    ks = np.arange(1, n_freqs - (n % 2 == 0))
    tol = 1e-9*domega
    ks = ks[(omega_sim[ks] >= omega_min - tol) & (omega_sim[ks] <= omega_max + tol)]

    P = np.zeros([n_dofs, n_freqs], dtype=complex)
    eye = np.eye(n_dofs)
    n_clipped = 0
    worst = 0.0
    for start in range(0, len(ks), batch_size):
        kb = ks[start:start + batch_size]
        S = np.asarray(S_fun(omega_sim[kb]))
        if component_scaling is not None:
            S = S*scale_mat
        if reg_factor is not None:
            norm_pre = np.linalg.norm(S)
            S = S + np.linalg.norm(S, axis=(1, 2))[:, np.newaxis, np.newaxis] * eye * reg_factor
            if norm_pre > 0 and (np.linalg.norm(S) - norm_pre)/norm_pre > 0.1:
                raise ValueError('Regularization causes significant increase in norm of S (10%). Please adjust.')
        if zero_limit is not None:
            keep = np.max(np.abs(S), axis=(1, 2)) > zero_limit
            kb, S = kb[keep], S[keep]
        if len(kb) == 0:
            continue

        try:
            B = np.linalg.cholesky(S)
        except LinAlgError:     # decompose one by one, using the nearest positive semi-definite factor where needed
            B = np.zeros_like(S)
            for i in range(S.shape[0]):
                try:
                    B[i] = cholesky(S[i], lower=True)
                except LinAlgError:
                    if not psd_fallback:
                        raise
                    B[i], min_eig = psd_factor(S[i])
                    n_clipped += 1
                    worst = min(worst, min_eig / np.mean(np.abs(np.diag(S[i]))))

        # Summation over all columns of B (B is not triangular where the PSD fallback was used)
        P[:, kb] = np.einsum('kjm,mk->jk', B, np.exp(1j*alpha[:, kb]))

    if n_clipped > 0:
        warnings.warn(f'Cross-spectral density not positive definite for {n_clipped} of {len(ks)} frequency components; '
                      f'negative eigenvalues clipped to zero (most negative: {worst:.2e} x mean diagonal).',
                      RuntimeWarning, stacklevel=2)

    p = np.fft.irfft(np.conj(P) * n * np.sqrt(domega/2), n=n, axis=1)

    # Periodic process: repeat the first sample so that t covers 0 ... tmax
    p = np.hstack([p, p[:, :1]])
    t = np.arange(n + 1)*dt

    if component_scaling is not None:
        p = p/np.tile(c[:, np.newaxis], reps=p.shape[1])

    if return_phase_angles:
        return p, t, alpha
    else:
        return p, t


def simulate_mdof_direct_legacy(S, omega, reg_factor=None):
    """
    Simulate time series from given cross-spectral density matrix, using direct summation.

    Formerly named `simulate_mdof_direct`. Slow (sums one cosine per DOF pair and frequency); kept for
    reference. For FFT-based simulation see `simulate_mdof` and `simulate_mdof_direct`.

    Parameters
    ----------------
    S : float
        cross-spectral density matrix (Ndofs x Ndofs x Nfreqs) as complex numpy array
    omega : float
        numpy array defining frequencies in rad/s
    reg_factor : float, optional
        to help the Cholesky decomposition to achieve a numerical solution, 
        a diagonal matrix with the norm of all frequency components of the matrix S scaled by the given factor
        - if no value is given (--> None imposed), no regularization is conducted; 
        used as input to function `spectrum_to_process` which decomposes the spectral density

    Returns
    ----------------
    p : float
        time history
    t : float
        numpy array with time axis values corresponding to `p`      
    
    """
    B = spectrum_to_process(S, reg_factor)

    # Summation
    domega = omega[1] - omega[0]

    t = fft_time(omega)
    p = np.zeros([B.shape[0], len(t)])
    phi = 2*np.pi * np.random.rand(B.shape[1], len(omega))     # one phase per (m, k), shared by all j

    for j in range(B.shape[0]):

        # Eq. 19 computed below for each j (all m: B is not triangular where the PSD fallback was used)
        for m in range(B.shape[1]):
            for k, omega_k in enumerate(omega):
                p[j, :] = p[j, :] + np.sqrt(2*domega) * np.real(B[j, m, k] * np.exp(1j*(omega_k*t + phi[m, k])))

    return p, t
    